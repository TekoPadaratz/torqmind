-- Migration 079: Screen permissions table + tenant_kiosk role
-- Phase 3: User access control
-- Idempotent: safe to re-run

BEGIN;

-- ?????????????????????????????????????????????????????????????
-- 1. Add tenant_kiosk to auth.users role CHECK constraint
-- ?????????????????????????????????????????????????????????????
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'ck_auth_users_role'
    AND pg_get_constraintdef(oid) ILIKE '%tenant_kiosk%'
  ) THEN
    ALTER TABLE auth.users DROP CONSTRAINT IF EXISTS ck_auth_users_role;
    ALTER TABLE auth.users ADD CONSTRAINT ck_auth_users_role
      CHECK (role = ANY(ARRAY[
        'platform_master','platform_admin','product_global',
        'channel_admin','tenant_admin','tenant_manager',
        'tenant_viewer','tenant_kiosk'
      ]));
  END IF;
END $$;

-- ?????????????????????????????????????????????????????????????
-- 2. Add tenant_kiosk to auth.user_tenants role CHECK constraint
-- ?????????????????????????????????????????????????????????????
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'ck_auth_user_tenants_role'
    AND pg_get_constraintdef(oid) ILIKE '%tenant_kiosk%'
  ) THEN
    ALTER TABLE auth.user_tenants DROP CONSTRAINT IF EXISTS ck_auth_user_tenants_role;
    ALTER TABLE auth.user_tenants ADD CONSTRAINT ck_auth_user_tenants_role
      CHECK (role = ANY(ARRAY[
        'platform_master','platform_admin','product_global',
        'channel_admin','tenant_admin','tenant_manager',
        'tenant_viewer','tenant_kiosk'
      ]));
  END IF;
END $$;

-- ?????????????????????????????????????????????????????????????
-- 3. Update role_scope constraint to include tenant_kiosk
--    (same scope rules as tenant_manager: empresa + filial required)
-- ?????????????????????????????????????????????????????????????
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'ck_auth_user_tenants_role_scope'
    AND pg_get_constraintdef(oid) ILIKE '%tenant_kiosk%'
  ) THEN
    ALTER TABLE auth.user_tenants DROP CONSTRAINT IF EXISTS ck_auth_user_tenants_role_scope;
    ALTER TABLE auth.user_tenants ADD CONSTRAINT ck_auth_user_tenants_role_scope CHECK (
      (
        role IN ('platform_master','platform_admin','product_global')
        AND channel_id IS NULL AND id_empresa IS NULL AND id_filial IS NULL
      )
      OR (
        role = 'channel_admin'
        AND channel_id IS NOT NULL AND id_empresa IS NULL AND id_filial IS NULL
      )
      OR (
        role = 'tenant_admin'
        AND channel_id IS NULL AND id_empresa IS NOT NULL AND id_filial IS NULL
      )
      OR (
        role IN ('tenant_manager','tenant_viewer','tenant_kiosk')
        AND channel_id IS NULL AND id_empresa IS NOT NULL AND id_filial IS NOT NULL
      )
    );
  END IF;
END $$;

-- ?????????????????????????????????????????????????????????????
-- 4. Create screen permissions table
-- ?????????????????????????????????????????????????????????????
CREATE TABLE IF NOT EXISTS auth.user_screen_permissions (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id     UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  screen_key  TEXT NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (user_id, screen_key)
);

CREATE INDEX IF NOT EXISTS idx_user_screen_permissions_user_id
  ON auth.user_screen_permissions(user_id);

-- ?????????????????????????????????????????????????????????????
-- 5. Add password_changed_at column
-- ?????????????????????????????????????????????????????????????
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'auth' AND table_name = 'users'
    AND column_name = 'password_changed_at'
  ) THEN
    ALTER TABLE auth.users ADD COLUMN password_changed_at TIMESTAMPTZ;
  END IF;
END $$;

-- ?????????????????????????????????????????????????????????????
-- 6. Backfill: give all existing tenant_manager users access to
--    ALL product screens (preserves current behavior).
--    Owner can restrict later via the user management UI.
-- ?????????????????????????????????????????????????????????????
INSERT INTO auth.user_screen_permissions (user_id, screen_key)
SELECT u.id, s.screen_key
FROM auth.users u
CROSS JOIN (
  VALUES
    ('dashboard_home'),
    ('sales'),
    ('cash'),
    ('fraud'),
    ('finance'),
    ('customers'),
    ('competitor_pricing'),
    ('goals_team')
) AS s(screen_key)
WHERE u.role = 'tenant_manager'
ON CONFLICT (user_id, screen_key) DO NOTHING;

COMMIT;
